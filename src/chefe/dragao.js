// Compressão LZW usada pelo formato GIF
function lzw(indices, minCode) {
  const clear = 1 << minCode;
  const eoi = clear + 1;
  let tam = minCode + 1;
  let prox = eoi + 1;
  let dic = new Map();
  const bytes = [];
  let acc = 0;
  let bits = 0;
  const emitir = (codigo) => {
    acc |= codigo << bits;
    bits += tam;
    while (bits >= 8) {
      bytes.push(acc & 255);
      acc >>>= 8;
      bits -= 8;
    }
  };
  emitir(clear);
  let atual = indices[0];
  for (let i = 1; i < indices.length; i++) {
    const k = indices[i];
    const chave = atual * 256 + k;
    if (dic.has(chave)) {
      atual = dic.get(chave);
    } else {
      emitir(atual);
      if (prox === 4096) {
        emitir(clear);
        tam = minCode + 1;
        prox = eoi + 1;
        dic = new Map();
      } else {
        if (prox >= (1 << tam)) tam++;
        dic.set(chave, prox++);
      }
      atual = k;
    }
  }
  emitir(atual);
  emitir(eoi);
  if (bits > 0) bytes.push(acc & 255);
  return bytes;
}

const u16 = (n) => [n & 255, (n >> 8) & 255];

function montarGif() {
  const larg = QUADROS[0][0].length * ESCALA;
  const alt = QUADROS[0].length * ESCALA;
  const out = [];
  out.push(...Buffer.from('GIF89a'));
  out.push(...u16(larg), ...u16(alt), 0xf3, 0, 0); // tabela global de 16 cores
  for (let i = 0; i < 16; i++) out.push(...(PALETA[i] || [0, 0, 0]));
  out.push(0x21, 0xff, 0x0b, ...Buffer.from('NETSCAPE2.0'), 0x03, 0x01, 0, 0, 0); // repete para sempre
  for (const quadro of QUADROS) {
    const pixels = [];
    for (const linha of quadro) {
      const expandida = [];
      for (const c of linha) for (let e = 0; e < ESCALA; e++) expandida.push(Number(c));
      for (let e = 0; e < ESCALA; e++) pixels.push(...expandida);
    }
    out.push(0x21, 0xf9, 0x04, 0x04, ...u16(ATRASO), 0, 0);
    out.push(0x2c, 0, 0, 0, 0, ...u16(larg), ...u16(alt), 0);
    out.push(4);
    const dados = lzw(pixels, 4);
    for (let i = 0; i < dados.length; i += 255) {
      const parte = dados.slice(i, i + 255);
      out.push(parte.length, ...parte);
    }
    out.push(0);
  }
  out.push(0x3b);
  return Buffer.from(out);
}

let cache = null;
const gif = () => cache || (cache = montarGif());
const anexo = () => new AttachmentBuilder(gif(), { name: NOME });

